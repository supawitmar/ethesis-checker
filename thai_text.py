"""ข้อความไทยที่หลายโมดูลใช้ร่วมกัน (checker.py อ่านเล่ม · ethesis_import.py อ่านข้อมูลอนุมัติ)"""
import re

# ฟอนต์ไทยรุ่นเก่าวาดตัวที่ต้อง "ขยับที่" ด้วย glyph สำรองที่มีรหัสในช่วง Private Use Area (PUA) U+F700-F71D
#   วรรณยุกต์/การันต์ลดต่ำเมื่อไม่มีสระบน ("ต่อ" "ได้" "วิทยานิพนธ์") · สระบน/วรรณยุกต์เยื้องซ้ายบนพยัญชนะหางสูง
#   (ป ฝ ฟ ฬ: "เป็น" "ปัจจุบัน") · สระล่างลดต่ำ · พยัญชนะตัดเชิงเมื่อมีสระล่าง (ญ ฐ ฎ ฏ) และ ฬ
# โปรแกรมทำ PDF บางตัวเก็บรหัส PUA นี้ไว้แทนอักษรจริง ถ้าไม่แปลงกลับ ระบบจะอ่านวรรณยุกต์หายทั้งเล่ม
# (เล่มจริง ต.ค. 2569: 10,134 ตัวใน 119 หน้า "ได้รับ" กลายเป็น "ไดรับ") และไฟล์ eThesis ทุกไฟล์ก็ใช้รหัสชุดนี้
# ตารางอ่านมาจากไฟล์ฟอนต์ TH Sarabun PSK และ TH Sarabun New เอง: ทุกรหัสชี้ไป glyph ชื่อ "uniXXXX.altN"
# คือ "ตัวสำรองของอักษร U+XXXX" จึงแปลงกลับได้ตรงตัว ไม่ต้องเดา — ตัวเลขขวาคือรหัสอักษรไทยที่ชื่อ glyph บอก
_PUA_GLYPH_OF = {
    0xF700: 0x0E10,                                                                 # ฐ ตัดเชิง
    0xF701: 0x0E34, 0xF702: 0x0E35, 0xF703: 0x0E36, 0xF704: 0x0E37,                 # ิ ี ึ ื เยื้องซ้าย
    0xF705: 0x0E48, 0xF706: 0x0E49, 0xF707: 0x0E4A, 0xF708: 0x0E4B, 0xF709: 0x0E4C,  # ่ ้ ๊ ๋ ์ ต่ำและเยื้องซ้าย
    0xF70A: 0x0E48, 0xF70B: 0x0E49, 0xF70C: 0x0E4A, 0xF70D: 0x0E4B, 0xF70E: 0x0E4C,  # ่ ้ ๊ ๋ ์ ต่ำ
    0xF70F: 0x0E0D,                                                                 # ญ ตัดเชิง
    0xF710: 0x0E31, 0xF711: 0x0E4D, 0xF712: 0x0E47,                                 # ั ํ ็ เยื้องซ้าย
    0xF713: 0x0E48, 0xF714: 0x0E49, 0xF715: 0x0E4A, 0xF716: 0x0E4B, 0xF717: 0x0E4C,  # ่ ้ ๊ ๋ ์ เยื้องซ้าย
    0xF718: 0x0E38, 0xF719: 0x0E39, 0xF71A: 0x0E3A,                                 # ุ ู ฺ ต่ำ
    0xF71B: 0x0E0E, 0xF71C: 0x0E0F, 0xF71D: 0x0E2C,                                 # ฎ ฏ ฬ
}
_THAI_PUA = {code: chr(thai) for code, thai in _PUA_GLYPH_OF.items()}


def fix_thai_pua(text):
    """แปลงรหัส PUA ของฟอนต์ไทยกลับเป็นอักษรไทยปกติ: "ได" + U+F70B + "รับ" → "ได้รับ" (ดูตารางข้างบน)"""
    return (text or '').translate(_THAI_PUA)

# สระอำเขียนในไฟล์ได้หลายแบบ แต่ตาเห็นเป็นสระอำเหมือนกันทุกแบบ (เจ้าหน้าที่สั่ง 6 ต.ค. 2569: นับทุกแบบเป็นสระอำ)
#   ำ            อักขระเดียว (U+0E33)  เล่มหลายเล่มเก็บแบบนี้
#   ํ + า        นิคหิตกับสระอา       ไฟล์ eThesis ทุกไฟล์ที่ตรวจดู และเล่มบางเล่ม
#   ํ + ่ + า     เมื่อมีวรรณยุกต์ นิคหิตมาก่อนวรรณยุกต์ (นํ้า) นี่คือลำดับที่ระบบอ่านได้จาก PDF จริง
#                 ส่วนลำดับมาตรฐานของ "น้ำ" คือ วรรณยุกต์ + ำ
#   ํ + ช่องว่าง + า  ระบบอ่าน PDF แล้วแทรกช่องว่างเองเมื่อตัว า วางห่างจากพยัญชนะเกินเกณฑ์ (เล่มจริงเล่มหนึ่ง 43 ที่)
#                 า ขึ้นต้นคำไม่ได้ ช่องว่างตรงนั้นจึงไม่มีอยู่จริงแน่นอน
# (ฟอนต์บางตัวเก็บนิคหิตเป็นช่องว่างกว้างศูนย์ — checker._thai_chars แปลงกลับเป็นนิคหิตก่อน แล้วจึงมาถึงที่นี่)
# รวมทุกแบบเป็น ำ ตัวเดียว (วรรณยุกต์ย้ายมาไว้หน้า ำ) — นิคหิตที่ไม่ได้ตามด้วยสระอา (สํสกฤต) ไม่ถูกแตะ
# และ า ที่ไม่มีนิคหิตนำหน้าก็ไม่ถูกแตะ (น้า คือสระอา ไม่ใช่สระอำ)
_SARA_AM_PARTS = re.compile('ํ([่-๋]*) *[าำ]')


def fold_sara_am(text):
    """รวมสระอำทุกแบบเป็น ำ ตัวเดียว: ํา → ำ · ํำ → ำ · นํ้า → น้ำ · จํ า → จำ"""
    return _SARA_AM_PARTS.sub(lambda m: m.group(1) + 'ำ', text or '')


def fold_sara_am_in(value):
    """fold_sara_am กับข้อความทุกตัวในโครงข้อมูล (str / list / tuple / dict) — ใช้กับข้อมูลอนุมัติทั้งชุด

    คืนโครงใหม่ ไม่แก้ของเดิม ค่าที่ไม่ใช่ข้อความ (ตัวเลข None) คงเดิม
    """
    if isinstance(value, str):
        return fold_sara_am(value)
    if isinstance(value, dict):
        return {key: fold_sara_am_in(item) for key, item in value.items()}
    if isinstance(value, list):
        return [fold_sara_am_in(item) for item in value]
    if isinstance(value, tuple):
        return tuple(fold_sara_am_in(item) for item in value)
    return value


# คำนำหน้าชื่อ "นักศึกษา" — ตัดออกก่อนเทียบเสมอ (เจ้าหน้าที่ ก.ค. 2569: "ชื่อนักศึกษา ให้ตรวจแบบไม่มีคำนำหน้า ถ้ามีให้เตือนส้ม")
# และตัดตั้งแต่ตอนอ่านไฟล์ eThesis เข้าฟอร์ม (เจ้าหน้าที่ 6 ต.ค. 2569: "หลักการเขียนในเล่ม มันต้องเขียนแบบไม่มี คำนำหน้า
# ถ้างั้นแก้ไข ให้การอ่านฟอร์มจากไฟล์ ที่แนบเข้าไปให้ตัดคำนำหน้านามทิ้งไปก่อนตรวจเลย") — ตัวเดียวกันทั้ง checker และ ethesis_import
#
# ยศทหาร/ตำรวจเขียนย่อได้หลายสิบแบบ (พ.จ.ต. จ.ส.อ. ร.ต.อ. น.ท. พล.ต.ต. ก.ท. ทพญ. ...) ไล่รายคำไม่มีวันครบ จึงจับ
# "อักษรไทย 1-4 ตัวคั่นด้วยจุด" เป็นรูปแบบเดียว — ชื่อคนไทยไม่มีจุดอยู่แล้ว จึงไม่ไปโดนชื่อจริง
# ฝั่งอังกฤษยศมักตามด้วยเลขชั้น ("CPO 3 ...") จึงเผื่อเลขท้ายคำนำหน้าไว้ด้วย · หน่วยที่นำหน้ายศตัดไปพร้อมยศ
# (Pol. = ตำรวจ · VDC = กองอาสารักษาดินแดน ไฟล์ eThesis เขียน "VDC Lt Col ..." ต.ค. 2569)
STUDENT_TITLE_PREFIX = re.compile(
    r'^\s*(?:'
    # "หญิง" ต่อท้ายยศได้ เช่น "ร.ต.อ.หญิง" / "พันเอกหญิง" ต้องตัดไปด้วย
    r'(?:[ก-๙]{1,4}\.\s*){1,4}(?:หญิง)?'
    r'|ว่าที่\s*(?:ร้อยตรี|ร้อยโท|ร้อยเอก|(?:[ก-๙]{1,4}\.\s*){1,4})(?:หญิง)?|'
    r'นายแพทย์|แพทย์หญิง|ทันตแพทย์|สัตวแพทย์|เภสัชกร|'   # ต้องมาก่อน "นาย"
    r'(?:พล|พัน|ร้อย|พันจ่า|จ่าสิบ|สิบ|นาวา|เรือ)(?:เอก|โท|ตรี)(?:หญิง)?|'
    r'นางสาว|นาง|นาย(?=\s|[ก-๙])|'
    r'(?:[A-Z]\.){2,4}'
    r'|Dental\s+Surgeon\b|Dentist\b|Pharmacist\b'
    r'|(?:(?:Pol|VDC)\.?\s*)?(?:Gen|Lt|Col|Maj|Capt|Sgt|Cpl|Pvt|CPO|PO|Cdr|Adm|Lieut|'
    r'Mr|Mrs|Miss|Ms|Dr)\b\.?'
    r')\s*\.?\s*\d*\s*', re.I)
# นาย/นาง/นางสาว ไม่ซ้อนกัน จึงตัดได้ครั้งเดียว — ไม่งั้นชื่อที่ขึ้นต้นด้วยคำเดียวกัน ("นางสาว นางนวล ...") ถูกกินต่อ
_HONORIFIC_TH = re.compile(r'^\s*(?:นางสาว|นาง|นาย)')


def strip_student_title(name):
    """ตัดคำนำหน้า/ยศออกจากชื่อนักศึกษา เหลือเฉพาะชื่อ-สกุล — ตัดซ้ำจนหมด ("VDC Lt Col ..." "ว่าที่ ร.ต. ดร. ...")"""
    s = (name or "").strip()
    prev, honorific_done = None, False
    while s and s != prev:
        prev = s
        if _HONORIFIC_TH.match(s):
            if honorific_done:
                break
            honorific_done = True
        s = STUDENT_TITLE_PREFIX.sub('', s, count=1).strip()
    return s or (name or "").strip()
