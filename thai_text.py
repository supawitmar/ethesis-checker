import re

# สระอำเขียนในไฟล์ได้หลายแบบ แต่ตาเห็นเป็นสระอำเหมือนกันทุกแบบ (เจ้าหน้าที่สั่ง 6 ต.ค. 2569: นับทุกแบบเป็นสระอำ)
#   ำ            อักขระเดียว (U+0E33)  เล่มหลายเล่มเก็บแบบนี้
#   ํ + า        นิคหิตกับสระอา       ไฟล์ eThesis ทุกไฟล์ที่ตรวจดู และเล่มบางเล่ม
#   ํ + ่ + า     เมื่อมีวรรณยุกต์ นิคหิตมาก่อนวรรณยุกต์ (นํ้า) นี่คือลำดับที่ระบบอ่านได้จาก PDF จริง
#                 ส่วนลำดับมาตรฐานของ "น้ำ" คือ วรรณยุกต์ + ำ
#   ํ + ช่องว่าง + า  ระบบอ่าน PDF แล้วแทรกช่องว่างเองเมื่อตัว า วางห่างจากพยัญชนะเกินเกณฑ์ (เล่มจริงเล่มหนึ่ง 43 ที่)
#                 า ขึ้นต้นคำไม่ได้ ช่องว่างตรงนั้นจึงไม่มีอยู่จริงแน่นอน
# (ฟอนต์บางตัวเก็บนิคหิตเป็นช่องว่างกว้างศูนย์ — checker._thai_chars แปลงกลับเป็นนิคหิตก่อน แล้วจึงมาถึงที่นี่)
# รวมทุกแบบเป็น ำ ตัวเดียว (วรรณยุกต์ย้ายมาไว้หน้า ำ) — นิคหิตที่ไม่ได้ตามด้วยสระอา (สํสกฤต) ไม่ถูกแตะ
# และ า ที่ไม่มีนิคหิตนำหน้าก็ไม่ถูกแตะ (น้า คือสระอา ไม่ใช่สระอำ)
_SARA_AM_PARTS = re.compile('ํ([่-๋]*) *[าำ]')


def fold_sara_am(text):
    """รวมสระอำทุกแบบเป็น ำ ตัวเดียว: ํา → ำ · ํำ → ำ · นํ้า → น้ำ · จํ า → จำ"""
    return _SARA_AM_PARTS.sub(lambda m: m.group(1) + 'ำ', text or '')


def fold_sara_am_in(value):
    """fold_sara_am กับข้อความทุกตัวในโครงข้อมูล (str / list / tuple / dict) — ใช้กับข้อมูลอนุมัติทั้งชุด

    คืนโครงใหม่ ไม่แก้ของเดิม ค่าที่ไม่ใช่ข้อความ (ตัวเลข None) คงเดิม
    """
    if isinstance(value, str):
        return fold_sara_am(value)
    if isinstance(value, dict):
        return {key: fold_sara_am_in(item) for key, item in value.items()}
    if isinstance(value, list):
        return [fold_sara_am_in(item) for item in value]
    if isinstance(value, tuple):
        return tuple(fold_sara_am_in(item) for item in value)
    return value
